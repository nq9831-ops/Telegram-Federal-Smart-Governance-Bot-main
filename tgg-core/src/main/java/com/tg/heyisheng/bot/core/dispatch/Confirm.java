package com.tg.heyisheng.bot.core.dispatch;

/**
 * 命令是否需要「执行前先确认」。
 *
 * <p>三态而非布尔，是因为有一类命令**按参数决定**：无参时是只读查询（不该打断），
 * 带参时是写操作（该确认）。{@code /data_breach} 就是典型——无参列出未通报事件，带参登记/记通报。
 * 命令级布尔无法区分这两种语义。
 */
public enum Confirm {

    /** 直接执行（默认）。绝大多数命令属于此类。 */
    NEVER,

    /** 一律先确认。用于不可逆或高影响的操作（资金、终态裁决、跨节点动作、关闭本群等）。 */
    ALWAYS,

    /**
     * 仅在**带操作数**时确认。
     *
     * <p>判据是「{@code commandArgs} 非空白」——不是「命令是否声明需要参数」
     * （注册表不掌握那个信息，靠它判断会引入一份会漂移的清单）。
     */
    WHEN_ARGS
}
