package com.tg.heyisheng.bot.credit;

/**
 * 处罚动作类型（模块七）。
 *
 * <p>按严重度递增排列。本阶段只负责<b>产出</b>处罚令；真实执行（警告/禁言/移除）
 * 与跨节点广播由消费方负责（本地执行随模块八接线，跨节点广播属模块八联邦治理）。
 */
public enum PenaltyType {

    /** 无处罚（分值未跨阈值）。 */
    NONE,

    /** 警告。 */
    WARN,

    /** 禁言（限时限制发言）。 */
    MUTE,

    /** 移出群。 */
    REMOVE,

    /**
     * 上报联邦。
     *
     * <p><b>最重一级</b>：按设计文档 §4.3，分值触底（≤0）时既本地移出、也上报联邦裁决；
     * 实现上合并为这一档——它同时意味着"本地移出 + 上报"，而非独立于 {@link #REMOVE} 的第三动作。
     */
    REPORT_TO_FEDERATION
}
